//! Symbol files (`game.sym`) as RGBDS, WLA-DX and other assemblers write them: one label
//! per line as `BANK:ADDR Name` in hex (`01:4000 Main.loop`), with `;` comments and
//! `[section]` headers (WLA-DX) skipped. The debugger shows the labels instead of
//! addresses and accepts them where it takes an address.

use std::collections::{BTreeMap, HashMap};

/// Where a label points: bank (ROM, cartridge RAM or work RAM bank, as the assembler
/// counts it) and address in the CPU's memory map.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct SymbolAddress {
    pub bank: u16,
    pub addr: u16,
}

#[derive(Debug, Clone, Default)]
pub struct Symbols {
    /// Labels by location; the first one read wins where several share a location.
    by_location: BTreeMap<SymbolAddress, String>,
    by_name: HashMap<String, SymbolAddress>,
    /// Same, with lower-case names, for typing them without minding the case.
    by_lower_name: HashMap<String, SymbolAddress>,
}

impl Symbols {
    /// Reads a symbol file; lines that are not labels are skipped.
    pub fn parse(text: &str) -> Self {
        let mut symbols = Self::default();
        for line in text.lines() {
            let line = line.split(';').next().unwrap_or("").trim();
            let Some((location, name)) = line.split_once(char::is_whitespace) else {
                continue;
            };
            let name = name.trim();
            let Some((bank, addr)) = location.split_once(':') else {
                continue;
            };
            let (Ok(bank), Ok(addr)) =
                (u16::from_str_radix(bank, 16), u16::from_str_radix(addr, 16))
            else {
                continue;
            };
            if name.is_empty() || name.contains(char::is_whitespace) {
                continue;
            }
            symbols.add(SymbolAddress { bank, addr }, name);
        }
        symbols
    }

    fn add(&mut self, at: SymbolAddress, name: &str) {
        self.by_location
            .entry(at)
            .or_insert_with(|| name.to_string());
        self.by_name.entry(name.to_string()).or_insert(at);
        self.by_lower_name.entry(name.to_lowercase()).or_insert(at);
    }

    pub fn len(&self) -> usize {
        self.by_name.len()
    }

    pub fn is_empty(&self) -> bool {
        self.by_name.is_empty()
    }

    /// All labels in address order (bank first), then by name.
    pub fn iter(&self) -> impl Iterator<Item = (SymbolAddress, &str)> {
        let mut all: Vec<(SymbolAddress, &str)> = self
            .by_name
            .iter()
            .map(|(name, at)| (*at, name.as_str()))
            .collect();
        all.sort_unstable();
        all.into_iter()
    }

    /// The label at `addr` in `bank`, if there is one.
    pub fn at(&self, bank: u16, addr: u16) -> Option<&str> {
        self.by_location
            .get(&SymbolAddress { bank, addr })
            .map(String::as_str)
    }

    /// The nearest label at or before `addr` in `bank` (within `max_offset` bytes), with
    /// the distance to it: `Main.loop+3`.
    pub fn before(&self, bank: u16, addr: u16, max_offset: u16) -> Option<(&str, u16)> {
        let low = SymbolAddress {
            bank,
            addr: addr.saturating_sub(max_offset),
        };
        let high = SymbolAddress { bank, addr };
        self.by_location
            .range(low..=high)
            .next_back()
            .map(|(at, name)| (name.as_str(), addr - at.addr))
    }

    /// Whether `name` is a label exactly as written (case included).
    pub fn at_name(&self, name: &str) -> bool {
        self.by_name.contains_key(name)
    }

    /// Where the label `name` points; exact case first, then any case.
    pub fn find(&self, name: &str) -> Option<SymbolAddress> {
        self.by_name
            .get(name)
            .or_else(|| self.by_lower_name.get(&name.to_lowercase()))
            .copied()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const RGBDS: &str = "\
; File generated by rgblink
00:0150 Start
00:0150 EntryPoint
01:4000 Main
01:4003 Main.loop
02:4000 OtherBank
00:c000 wCounter
00:ff80 hVBlankFlag ; trailing comment
garbage line
[labels]
";

    #[test]
    fn reads_rgbds_and_wla_symbols() {
        let s = Symbols::parse(RGBDS);
        assert_eq!(s.len(), 7);
        assert_eq!(s.at(0, 0x0150), Some("Start"), "the first label wins");
        assert_eq!(s.at(1, 0x4003), Some("Main.loop"));
        assert_eq!(s.at(2, 0x4000), Some("OtherBank"));
        assert_eq!(s.at(1, 0x4001), None);
        assert_eq!(
            s.find("EntryPoint"),
            Some(SymbolAddress {
                bank: 0,
                addr: 0x150
            })
        );
        assert_eq!(s.find("main.LOOP").map(|a| a.addr), Some(0x4003));
        assert_eq!(s.find("hVBlankFlag").map(|a| a.addr), Some(0xFF80));
        assert_eq!(s.find("nope"), None);
    }

    #[test]
    fn nearest_label_before() {
        let s = Symbols::parse(RGBDS);
        assert_eq!(s.before(1, 0x4005, 16), Some(("Main.loop", 2)));
        assert_eq!(s.before(1, 0x4003, 16), Some(("Main.loop", 0)));
        assert_eq!(s.before(1, 0x4100, 16), None, "too far away");
        assert_eq!(s.before(2, 0x3FFF, 16), None, "other banks don't count");
    }
}
